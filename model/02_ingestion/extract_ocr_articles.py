"""Convert OCR page text into article JSON without silently filling gaps.

The OCR step is intentionally explicit: callers provide a directory of page
text files generated by Tesseract, and every extracted article keeps its page
and ``source_extraction`` marker for later human review.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ARTICLE_RE = re.compile(
    r"^\s*[|F‘I’`´]?\s*Article\s+(1er|ler|premier|[0-9]+)\s*[:;.]?\s*(.*)$",
    re.IGNORECASE,
)
HEADING_RE = re.compile(r"^\s*(TITRE|CHAPITRE|SECTION|LIVRE)\b\s*(.*)$", re.IGNORECASE)


def extract_pages(ocr_dir: Path, doc_id: str, document: str) -> list[dict]:
    pages = sorted(ocr_dir.glob("page-*.txt"))
    articles: list[dict] = []
    current: dict | None = None
    headings = {"titre": "", "chapitre": "", "section": ""}

    def flush() -> None:
        nonlocal current
        if current is None:
            return
        current["texte"] = re.sub(r"\s+", " ", current["texte"]).strip()
        if current["texte"]:
            articles.append(current)
        current = None

    for page_path in pages:
        page_match = re.search(r"(\d+)", page_path.stem)
        page_number = int(page_match.group(1)) if page_match else None
        for raw_line in page_path.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = raw_line.strip()
            if not line:
                continue
            heading = HEADING_RE.match(line)
            if heading:
                key = heading.group(1).lower()
                headings[key] = heading.group(2).strip()
                if key in {"titre", "chapitre"}:
                    # Headings are metadata, not article text.
                    continue
            match = ARTICLE_RE.match(line)
            if match:
                flush()
                number = match.group(1).lower()
                if number in {"1er", "ler", "premier"}:
                    number = "1"
                current = {
                    "doc_id": doc_id,
                    "article_ref": f"Article {number}",
                    "titre": headings["titre"],
                    "chapitre": headings["chapitre"],
                    "section": headings["section"],
                    "texte": match.group(2),
                    "page": page_number,
                    "document": document,
                    "source_extraction": "ocr_tesseract_eng",
                }
                continue
            if current is not None:
                current["texte"] += " " + line
        # Do not flush at a page break: articles commonly span pages.
    flush()
    for index, article in enumerate(articles):
        article["id"] = f"{doc_id}_art_{index:04d}"
    return articles


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("ocr_dir", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--doc-id", required=True)
    parser.add_argument("--document", required=True)
    args = parser.parse_args()
    articles = extract_pages(args.ocr_dir, args.doc_id, args.document)
    args.output.write_text(json.dumps(articles, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(articles)} articles extraits → {args.output}")


if __name__ == "__main__":
    main()
